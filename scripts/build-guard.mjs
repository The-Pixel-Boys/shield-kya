#!/usr/bin/env node
/**
 * Build plugins/kya-guard/dist/guard.mjs from src/guard-entry.ts (one file, no dependencies, no network code).
 * The host variants for Cursor, Copilot CLI and Gemini CLI get a byte-identical copy (a plugin folder cannot read a file outside itself).
 *   node scripts/build-guard.mjs           write the bundle and its copies
 *   node scripts/build-guard.mjs --check   fail when a committed file differs from a fresh build (stale check)
 * Also exports buildGuard() for test/guard-bundle.test.ts.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const PKG = join(fileURLToPath(import.meta.url), "..", "..");
export const BUNDLE = join(PKG, "plugins", "kya-guard", "dist", "guard.mjs");
/** Variant folders that carry the same bundle. Keep in step with scripts/ci/kya-mirror-includes.txt (a test checks it). */
export const VARIANT_DIRS = ["kya-guard-cursor", "kya-guard-copilot", "kya-guard-gemini"];
export const COPIES = VARIANT_DIRS.map((d) => join(PKG, "plugins", d, "dist", "guard.mjs"));

/** The bundle text. Deterministic: same sources and same esbuild give the same bytes. */
export async function buildGuard() {
  const r = await build({
    absWorkingDir: PKG, // the bundle comments carry paths relative to this folder, so the build does not depend on the caller's cwd
    entryPoints: [join(PKG, "src", "guard-entry.ts")],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    minify: false,
    legalComments: "none",
    write: false,
    logLevel: "silent",
    banner: { js: "// KYA Guard: generated by scripts/build-guard.mjs from sdks/kya/src. Do not edit. MIT license." },
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const fresh = await buildGuard();
  if (process.argv.includes("--check")) {
    for (const file of [BUNDLE, ...COPIES]) {
      let committed = "";
      try { committed = readFileSync(file, "utf8"); } catch { /* missing */ }
      if (committed !== fresh) {
        console.error(`${file.slice(PKG.length + 1)} is stale. Run: pnpm run build:guard`);
        process.exit(1);
      }
    }
    console.log(`guard bundle and ${COPIES.length} copies are current (${Buffer.byteLength(fresh)} bytes)`);
  } else {
    for (const file of [BUNDLE, ...COPIES]) {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, fresh);
      console.log(`wrote ${file} (${Buffer.byteLength(fresh)} bytes)`);
    }
  }
}
