const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
export const vendorName = (v) => VENDOR_NAME[v] ?? cap(v);

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#39;");
/** JSON for a script tag: no raw `<`, `>` or `&`, so the text can never close the tag. */
const jsonForScript = (o) => JSON.stringify(o).replace(/</g, "\\u003c").replace(/>/g, "\\u003e").replace(/&/g, "\\u0026");

/** Rule id to plain label: never-list rows first, then the guard pack (the order src/card.ts ruleLabel uses). */
export function loadLabels(root) {
  const labels = new Map();
  const never = readFileSync(join(root, "src", "never-list-input.ts"), "utf8");
  for (const m of never.matchAll(/\{ id: "([a-z0-9-]+)", group: "[a-z]+", label: "([^"]+)"/g)) labels.set(m[1], m[2]);
  const guard = readFileSync(join(root, "src", "guard-pack.ts"), "utf8");
  const at = guard.indexOf("const LABELS:");
  const end = guard.indexOf("\n};", at);
  if (at < 0 || end < 0) throw new Error("src/guard-pack.ts: the LABELS table was not found");
  for (const m of guard.slice(at, end).matchAll(/^\s+"([a-z0-9-]+)": "([^"]+)",?$/gm)) if (!labels.has(m[1])) labels.set(m[1], m[2]);
  return labels;
}
/** What the call tries to do: the replay's own `label` when it has one, else the label of its rule. */
export const callLabel = (r, labels) => r.label ?? labelOf(r.rule, labels);
export function labelOf(rule, labels) {
  const fixed = labels.get(rule);
  if (fixed) return fixed;
  if (rule.startsWith("secret-read-")) return "read a credentials file";
  if (rule.startsWith("secret-write-")) return "write a secret into a file";
  if (rule.startsWith("exfil-")) return "send secrets over the network";
  throw new Error(`no label for rule ${rule}: add it to LABELS in src/guard-pack.ts`);
}

/**
 * Shapes of secrets that scanners know (GitHub tokens, AWS key ids, Stripe and Slack tokens, private key headers). Some
 * replays show a placeholder with such a shape. The first character is written as a numeric character reference, so the
 * browser shows the same text but the bytes of the file match no scanner (gitleaks, GitHub push protection).
 */
export const SECRET_SHAPES = [
  /gh[pousr]_[0-9a-zA-Z]{20,}/g,
  /github_pat_\w{20,}/g,
  /\b(?:AKIA|ASIA|ABIA|ACCA|A3T[A-Z0-9])[A-Z0-9]{12,}/g,
  /\b[sr]k_(?:live|test|prod)_[0-9a-zA-Z]{8,}/g,
  /xox[abeoprs]-[0-9a-zA-Z-]{8,}/g,
  /-----BEGIN[ A-Z0-9_-]{0,40}(?:PRIVATE KEY|PGP PRIVATE KEY BLOCK)-----/g,
];
export function maskSecrets(text) {
  let out = text;
  for (const shape of SECRET_SHAPES) out = out.replace(shape, (m) => `&#${m.codePointAt(0)};${m.slice(1)}`);
  return out;
}

/** Inline markdown of a host recipe: `code`, **bold**, [text](link). Everything else is text, escaped. */
function inlineMd(text, base) {
  let out = "";
  let last = 0;
  for (const m of text.matchAll(/`([^`]+)`|\*\*([^*]+)\*\*|\[([^\]]+)\]\(([^)]+)\)/g)) {
    out += esc(text.slice(last, m.index));
    last = m.index + m[0].length;
    if (m[1] !== undefined) out += `<code>${esc(m[1])}</code>`;
    else if (m[2] !== undefined) out += `<strong>${esc(m[2])}</strong>`;
    else {
      const href = /^https:\/\//.test(m[4]) ? m[4] : /^[\w./-]+\.md(#[\w-]+)?$/.test(m[4]) ? `${REPO}/blob/main/docs/${base}${m[4]}`.replace(/\/[^/]+\/\.\.\//g, "/") : "";
      out += href ? `<a href="${esc(href)}" rel="noopener">${esc(m[3])}</a>` : esc(m[3]);
    }
  }
  return out + esc(text.slice(last));
}

/** One host recipe: name, plain text of its honesty note as HTML paragraphs, and the recipe link. */
export function loadHosts(root) {
  const dir = join(root, "docs", "hosts");
  const hosts = [];
  for (const f of readdirSync(dir).filter((x) => x.endsWith(".md") && x !== "claude-plugin.md").sort()) {
    const key = f.replace(/\.md$/, "");
    const text = readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n");
    const h1 = /^# (.+)$/m.exec(text)?.[1] ?? key;
    const lines = text.split("\n");
    const at = lines.findIndex((l) => /^#{2,3} Honesty note\s*$/.test(l));
    let note = "";
    if (at >= 0) {
      const body = [];
      for (let i = at + 1; i < lines.length && !/^#{1,6} /.test(lines[i]); i++) body.push(lines[i]);
      note = body.join("\n").trim().split(/\n{2,}/).filter(Boolean).map((p) => `<p>${inlineMd(p.replace(/\n/g, " "), "hosts/")}</p>`).join("\n");
    }
    hosts.push({ key, name: HOST_NAME[key] ?? h1, note, recipe: `${REPO}/blob/main/docs/hosts/${f}` });
  }
  return hosts;
}

const RESULT = {
  deny: ["Stopped", "the local hook denies the call and names the rule."],
  ask: ["Held", "the local hook asks the person before the call runs. On a host without an ask contract the same rule denies."],
};
const firstSentence = (s) => /^.*?[.!?](?=\s|$)/.exec(s)?.[0] ?? s;

const page = (path, type, key, title, description, body, jsonld, index, extra = {}) => ({ path, type, key, title, description, body, jsonld, index, ...extra });

function techArticle({ title, description, path, date, about }) {
  return {
    "@context": "https://schema.org",
    "@type": "TechArticle",
    headline: title,
    description,
    url: SITE + path,
    mainEntityOfPage: SITE + path,
    datePublished: date,
    inLanguage: "en",
    about,
    author: { "@type": "Organization", name: "Shield Agent", url: SITE },
    publisher: { "@type": "Organization", name: "Shield Agent", url: SITE },
  };
}

/** The first clause of a fix, 30 characters or more: up to the first comma or full stop that is not inside brackets. */
export function firstClause(fix) {
  let depth = 0;
  for (let i = 0; i < fix.length; i++) {
    const c = fix[i];
    if (c === "(" || c === "[" || c === "{") depth++;
    else if (c === ")" || c === "]" || c === "}") depth--;
    else if (depth === 0 && i >= 30 && (c === "," || (c === "." && (i + 1 === fix.length || fix[i + 1] === " ")))) return fix.slice(0, i);
  }
  return fix.replace(/\.$/, "");
}
/** Meta description: the replay title, the vendor and the first clause of the fix, at most 155 characters. */
export function describe(r) {
  const head = `${r.title}. ${cap(vendorName(r.vendor))} fix: `;
  let clause = firstClause(r.fix);
  clause = clause.charAt(0).toLowerCase() + clause.slice(1);
  if (`${head}${clause}.`.length <= 155) return `${head}${clause}.`;
  const room = 155 - head.length - 3;
  const part = clause.slice(0, room);
  // Cut before a command or a bracket where there is a natural break, else at a word.
  const at = Math.max(part.lastIndexOf(" with "), part.lastIndexOf(" that "), part.lastIndexOf(" ("));
  return `${head}${(at >= 25 ? part.slice(0, at) : part.replace(/\s+\S*$/, "")).trimEnd()}...`;
}

const code = (s) => `<pre><code>${esc(s)}</code></pre>`;
const inputText = (r) => (typeof r.input.command === "string" ? r.input.command : JSON.stringify(r.input, null, 2));

/** All pages for the replays (controls get no page) and the host recipes. */
export function buildPages(replays, labels, hosts) {
  const hostKeys = new Set(hosts.map((h) => h.key));
  const subjects = replays.filter((r) => r.kind !== "control").sort((a, b) => a.id.localeCompare(b.id));
  const labelCount = new Map();
  for (const r of subjects) labelCount.set(callLabel(r, labels), (labelCount.get(callLabel(r, labels)) ?? 0) + 1);
  const byVendor = new Map();
  for (const r of subjects) byVendor.set(r.vendor, [...(byVendor.get(r.vendor) ?? []), r]);
  const pathOf = (r) => `/replays/${r.id}`;
  /** A title of about 60 characters or less. A shared rule label cannot make a unique title, so the replay title does. */
  const titleOf = (r) => {
    const label = callLabel(r, labels);
    if (labelCount.get(label) === 1) return `Stop an agent trying to ${label}`;
    const asked = `${r.title}: how to stop it`;
    return asked.length <= 60 ? asked : r.title.length <= 60 ? r.title : `Stop an agent trying to ${label}`;
  };
  const link = (r) => `<a href="${esc(pathOf(r))}">${esc(r.title)}</a>`;
  const pages = [];

  for (const r of subjects) {
    if (!hostKeys.has(r.host)) throw new Error(`${r.id}: host ${r.host} has no recipe in docs/hosts/`);
    const label = callLabel(r, labels);
    const title = titleOf(r);
    const host = hosts.find((h) => h.key === r.host);
    const [result, resultText] = RESULT[r.expect] ?? [];
    if (!result || r.status === "gap") throw new Error(`${r.id}: only a stopped or held replay can have a page`);
    const group = byVendor.get(r.vendor);
    const at = group.indexOf(r);
    const related = [1, 2, 3].map((i) => group[(at + i) % group.length]).filter((x, i, a) => x !== r && a.indexOf(x) === i);
    const kind = r.kind === "incident" ? "Incident replay" : "Command replay (a class of call, not one reported incident)";
    const sent = `The agent sends it through its ${esc(r.tool)} tool, and it involves ${esc(vendorName(r.vendor))}.`;
    const happens = r.kind === "incident"
      ? `<p>${esc(r.title)}, reported on ${esc(r.date)}. The call below tries to ${esc(label)}. ${sent}</p>\n<p>Sources: ${r.sources.map((s, i) => `<a href="${esc(s)}" rel="noopener">${i + 1}</a>`).join(" ")}</p>`
      : `<p>${esc(r.title)}. The call below tries to ${esc(label)}. ${sent}</p>`;
    const plugin = PLUGIN_INSTALL[r.host];
    const body = [
      `<!-- ${HEADER} -->`,
      `<article class="replay-page" data-replay="${esc(r.id)}">`,
      `<header><p class="eyebrow">${kind}</p><h1>${esc(title)}</h1></header>`,
      `<section id="what-happens"><h2>What happens</h2>\n${happens}\n</section>`,
      `<section id="the-call"><h2>The call</h2>\n${r.reconstructed ? `<p><em>${RECONSTRUCTED}</em></p>\n` : ""}${code(inputText(r))}\n<p>Tool: <code>${esc(r.tool)}</code>. The replay uses placeholder tokens and hosts only.</p>\n</section>`,
      `<section id="fix"><h2>Fix it without us</h2>\n<p>${esc(r.fix)}</p>\n</section>`,
      `<section id="what-kya-does"><h2>What KYA does</h2>\n<p>Replay result: <strong>${result}</strong>. In the replay test, ${esc(resultText)}</p>\n<p>Rule <a href="${GUARD_PACK_DOC}" rel="noopener"><code>${esc(r.rule)}</code></a>, first stopped in version <code>${esc(r.since)}</code>.</p>\n<p>The hook is local and advisory. It fails open: if kya breaks or times out, the call goes ahead.</p>\n</section>`,
      `<section id="install"><h2>Install</h2>\n${plugin ? `<p>For ${esc(host.name)}, the host this replay ran on:</p>\n${code(plugin.join("\n"))}\n<p>For any host:</p>\n` : `<p>The install for any host (this replay ran on ${esc(host.name)}):</p>\n`}${code(GENERIC_INSTALL)}\n</section>`,
      `<section id="related"><h2>Related replays</h2>\n${related.length ? `<ul>\n${related.map((x) => `<li>${link(x)}</li>`).join("\n")}\n</ul>\n` : ""}<p><a href="/replays/vendor/${esc(r.vendor)}">All ${esc(vendorName(r.vendor))} replays</a> | <a href="/replays/agent/${esc(r.host)}">Replays on ${esc(host.name)}</a> | <a href="/replays">All replays</a></p>\n</section>`,
      `</article>`,
      "",
    ].join("\n");
    const description = describe(r);
    pages.push(page(pathOf(r), r.kind, r.id, title, description, body, techArticle({ title, description, path: pathOf(r), date: r.date, about: vendorName(r.vendor) }), true));
  }

  for (const [vendor, group] of [...byVendor].sort((a, b) => a[0].localeCompare(b[0]))) {
    const name = vendorName(vendor);
    const path = `/replays/vendor/${vendor}`;
    const incidents = group.filter((r) => r.kind === "incident").length;
    const title = `Coding agent risks with ${name}: replays and fixes`;
    const description = `${group.length} coding-agent replays involving ${name}: what happens, the fix without any extra tool, and the Shield KYA replay result.`;
    const body = [
      `<!-- ${HEADER} -->`,
      `<article class="replay-page replay-hub" data-vendor="${esc(vendor)}">`,
      `<header><p class="eyebrow">Vendor replays</p><h1>${esc(title)}</h1></header>`,
      `<p>${group.length} ${group.length === 1 ? "replay involves" : "replays involve"} ${esc(name)}: ${incidents} reported ${incidents === 1 ? "incident" : "incidents"} and ${group.length - incidents} command ${group.length - incidents === 1 ? "class" : "classes"}. Each one shows the call, a fix that needs no extra tool, and what KYA did in the replay.</p>`,
      `<ul class="replay-list">`,
      ...group.map((r) => `<li><h2>${link(r)}</h2>\n<p><strong>Fix:</strong> ${esc(r.fix)}</p>\n<p>Replay result: ${RESULT[r.expect][0]}.</p></li>`),
      `</ul>`,
      `<p><a href="/replays">All replays</a></p>`,
      `</article>`,
      "",
    ].join("\n");
    pages.push(page(path, "vendor", vendor, title, description, body, techArticle({ title, description, path, date: group.map((r) => r.date).sort().at(-1), about: name }), group.length >= MIN_HUB, { label: name, count: group.length }));
  }

  for (const h of hosts) {
    const tested = subjects.filter((r) => r.host === h.key);
    const path = `/replays/agent/${h.key}`;
    const title = `${h.name}: which KYA replays were tested`;
    const description = `Which Shield KYA replays ran on ${h.name}, and what the ${h.name} setup page says KYA can and cannot see.`;
    const hostsUsed = [...new Set(subjects.map((r) => r.host))].map((k) => hosts.find((x) => x.key === k).name);
    const plain = tested.length
      ? `<p>${tested.length === subjects.length ? `All ${tested.length} replays ran on ${esc(h.name)} only. No replay has run on any other host.` : `${tested.length} of ${subjects.length} replays ran on ${esc(h.name)}.`}</p>`
      : `<p>No replay has run on ${esc(h.name)}. All ${subjects.length} replays ran on ${esc(hostsUsed.join(" and "))} only, so this page makes no claim about ${esc(h.name)}.</p>`;
    const plugin = PLUGIN_INSTALL[h.key];
    const body = [
      `<!-- ${HEADER} -->`,
      `<article class="replay-page replay-hub" data-agent="${esc(h.key)}">`,
      `<header><p class="eyebrow">Agent replays</p><h1>${esc(title)}</h1></header>`,
      `<section id="tested"><h2>Replays tested on ${esc(h.name)}</h2>\n${plain}`,
      tested.length ? `<ul class="replay-list">\n${tested.map((r) => `<li>${link(r)} (${RESULT[r.expect][0]})</li>`).join("\n")}\n</ul>` : "",
      `</section>`,
      h.note ? `<section id="coverage"><h2>What the ${esc(h.name)} setup page says about coverage</h2>\n${h.note}\n<p>Source: <a href="${esc(h.recipe)}" rel="noopener">the ${esc(h.name)} recipe</a>.</p>\n</section>` : `<section id="coverage"><h2>${esc(h.name)} setup</h2>\n<p>See <a href="${esc(h.recipe)}" rel="noopener">the ${esc(h.name)} recipe</a> for what KYA covers on this host.</p>\n</section>`,
      `<section id="install"><h2>Install</h2>\n${plugin ? `<p>The plugin for ${esc(h.name)}:</p>\n${code(plugin.join("\n"))}\n<p>For any host:</p>\n` : ""}${code(GENERIC_INSTALL)}\n</section>`,
      `<p><a href="/replays">All replays</a></p>`,
      `</article>`,
      "",
    ].filter((x) => x !== "").join("\n");
    pages.push(page(path, "agent", h.key, title, description, body, techArticle({ title, description, path, date: subjects.map((r) => r.date).sort().at(-1), about: h.name }), tested.length >= 1, { label: h.name, count: tested.length }));
  }

  for (const key of ["path", "title", "description"]) {
    const seen = new Map();
    for (const p of pages) {
      if (seen.has(p[key])) throw new Error(`replay pages: ${key} is not unique: ${p[key]} (${seen.get(p[key])} and ${p.key})`);
      seen.set(p[key], p.key);
    }
  }
  return pages;
}

const fileOf = (p) => (p.type === "vendor" ? `vendor-${p.key}.html` : p.type === "agent" ? `agent-${p.key}.html` : `${p.key}.html`);

/** The generated files as { path relative to the package root: text }. Throws when a replay file is not valid. */
export function generate(root) {
  const pages = buildPages(loadReplays(join(root, "replays")), loadLabels(root), loadHosts(root));
  const files = {};
  const manifest = {
    _generated: HEADER,
    pages: pages.map((p) => {
      files[`${PAGES_DIR}/${fileOf(p)}`] = maskSecrets(p.body);
      return { path: p.path, type: p.type, key: p.key, title: p.title, description: p.description, index: p.index, file: fileOf(p), label: p.label ?? "", count: p.count ?? 0, jsonld: jsonForScript(p.jsonld) };
    }),
  };
  files[MANIFEST] = `${JSON.stringify(manifest, null, 2)}\n`;
  return files;
}

/** Problems: a generated file that is missing or differs, and a file in replays/pages/ that nothing generates (an orphan). */
export function stale(root) {
  const want = generate(root);
  const bad = Object.entries(want).filter(([p, text]) => !existsSync(join(root, p)) || readFileSync(join(root, p), "utf8") !== text).map(([p]) => p);
  const dir = join(root, PAGES_DIR);
  const orphans = existsSync(dir) ? readdirSync(dir).map((f) => `${PAGES_DIR}/${f}`).filter((p) => !(p in want)) : [];
  return [...bad, ...orphans.map((p) => `${p} (orphan: no replay generates it)`)];
}
