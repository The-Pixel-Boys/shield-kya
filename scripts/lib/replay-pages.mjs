export const MANIFEST = `${PAGES_DIR}/pages.json`;
export const GUARD_PACK_DOC = `${REPO}/blob/main/docs/guard-pack.md`;
const HEADER = "Generated by `pnpm sync:replay-pages` from replays/*.yaml and docs/hosts/*.md. Do not edit by hand.";
const RECONSTRUCTED = "Reconstructed from the public account";
const GENERIC_INSTALL = "npm i -g @shield-agent/kya@latest && kya start";
/** A hub with fewer replays than this is a thin page: it is built but not indexed. */
export const MIN_HUB = 2;

