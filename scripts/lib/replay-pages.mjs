// Replay pages (acquisition build B1b): one public page per incident and class replay, one hub per vendor and one
// per host recipe. Pure functions: scripts/replay-pages.mjs writes the files, test/replay-pages.test.ts checks them.
// Every word on a page comes from replays/*.yaml, the rule labels in src/, docs/hosts/*.md or a template below.
// No dependencies. The output is plain escaped HTML fragments plus pages.json (the manifest the Spring site reads).
