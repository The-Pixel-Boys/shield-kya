import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { assertInsideRoot, jailRoot } from "./path-jail.js";
import { assertSandboxId } from "./id.js";

/**
 * OpenShell policy rendering (NVIDIA OpenShell, github.com/NVIDIA/OpenShell).
 * Policy documents are `version: 1`, at most 4 MiB, and reject unknown fields:
 * keep this YAML minimal and add nothing the OpenShell schema does not define.
 * Filesystem rules lock at sandbox start; `network_policies` hot-reload.
 */

export const OPENSHELL_WORKDIR = "/workspace";

export function openshellPolicyPath(root: string, sandboxId: string): string {
  const id = assertSandboxId(sandboxId);
  const jailed = jailRoot(root);
  const path = join(jailed, ".kya", "openshell", `policy-${id}.yaml`);
  return assertInsideRoot(path, jailed, "openshell policy");
}

/**
 * Default-deny network policy. The KYA tool registry (src/mcp-servers.ts)
 * carries the per-server MCP tool allowlist but no egress shape yet, so the
 * seeded policy denies everything; extend `network_policies` from that
 * registry once it exposes network destinations.
 */
export function renderOpenshellPolicy(input: {
  readonly sandboxId: string;
  readonly workdir: string;
}): string {
  const id = assertSandboxId(input.sandboxId);
  const workdir = input.workdir.startsWith("/") ? input.workdir : OPENSHELL_WORKDIR;
  const readOnly = ["/usr", "/lib", "/lib64", "/bin", "/sbin", "/etc"];
  const lines: string[] = [
    `# Generated by KYA for ${id} (kya sandbox spawn, KYA_SANDBOX=openshell). Do not edit by hand.`,
    `# OpenShell policy version 1. Filesystem rules lock at sandbox start;`,
    `# network_policies hot-reload. Network is default-deny: allowlist seeds`,
    `# belong to the MCP server registry (src/mcp-servers.ts).`,
    `version: 1`,
    `filesystem:`,
  ];
  for (const path of readOnly) {
    lines.push(`  - path: ${path}`, `    access: read_only`);
  }
  lines.push(`  - path: ${workdir}`, `    access: read_write`);
  lines.push(`network_policies: []`, `process:`, `  run_as_user: "nobody"`, ``);
  const yaml = lines.join("\n");
  if (Buffer.byteLength(yaml, "utf8") > 4 * 1024 * 1024) {
    throw new Error(`openshell policy exceeds 4 MiB for ${id}`);
  }
  return yaml;
}

/** Render and write the policy file; returns the jailed path passed to --policy. */
export function writeOpenshellPolicy(root: string, sandboxId: string): string {
  const path = openshellPolicyPath(root, sandboxId);
  mkdirSync(join(path, ".."), { recursive: true });
  writeFileSync(path, renderOpenshellPolicy({ sandboxId, workdir: OPENSHELL_WORKDIR }), "utf8");
  return path;
}
