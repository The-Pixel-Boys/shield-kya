/**
 * Replay pages generator (acquisition build B1b). The pages are built from replays/*.yaml, the rule labels in src/ and
 * docs/hosts/*.md, and nothing else. These tests build in a scratch package root that holds only those inputs, so a page
 * that needed a hand-written file elsewhere would fail here. The CLI check is run as CI runs it (pnpm check:replay-pages).
 */
import { afterAll, describe, expect, it } from "vitest";
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ruleLabel } from "../src/card.js";
// @ts-expect-error plain .mjs script, no type declarations
import { loadReplays } from "../scripts/lib/replays.mjs";
// @ts-expect-error plain .mjs script, no type declarations
import { MANIFEST, MIN_HUB, PAGES_DIR, buildPages, callLabel, describe as describePage, firstClause, generate, labelOf, loadHosts, loadLabels, maskSecrets, stale } from "../scripts/lib/replay-pages.mjs";

const PKG = join(import.meta.dirname, "..");
const SCRIPT = join(PKG, "scripts", "replay-pages.mjs");
const scratch: string[] = [];
afterAll(() => {
  for (const d of scratch) rmSync(d, { recursive: true, force: true });
});

/** A package root with only the inputs of the generator, so nothing else can leak into a page. */
function inputsOnly(): string {
  const root = mkdtempSync(join(tmpdir(), "kya-replay-pages-"));
  scratch.push(root);
  cpSync(join(PKG, "replays"), join(root, "replays"), { recursive: true, filter: (s) => !s.includes(`${join("replays", "pages")}`) });
  cpSync(join(PKG, "docs", "hosts"), join(root, "docs", "hosts"), { recursive: true });
  mkdirSync(join(root, "src"));
  for (const f of ["never-list-input.ts", "guard-pack.ts"]) cpSync(join(PKG, "src", f), join(root, "src", f));
  return root;
}
const check = (root: string) => spawnSync(process.execPath, [SCRIPT, "--check", "--root", root], { encoding: "utf8" });
const write = (root: string) => spawnSync(process.execPath, [SCRIPT, "--root", root], { encoding: "utf8" });

interface Page { path: string; type: string; key: string; title: string; description: string; index: boolean; file: string; label: string; count: number; jsonld: string }
const files = generate(PKG) as Record<string, string>;
const manifest = JSON.parse(files[MANIFEST]) as { _generated: string; pages: Page[] };
const replays = loadReplays(join(PKG, "replays")) as { id: string; kind: string; vendor?: string; fix?: string; rule: string; reconstructed?: boolean; title: string; host: string; since: string; expect: string; sources?: string[]; input: { command?: string } }[];
const subjects = replays.filter((r) => r.kind !== "control");
const body = (p: Page): string => files[`${PAGES_DIR}/${p.file}`];
const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#39;");

describe("replay pages: what is built", () => {
  it("builds one page per incident and class (51 today), one per vendor and one per host recipe, and none for a control", () => {
    const of = (t: string) => manifest.pages.filter((p) => p.type === t);
    expect(of("incident")).toHaveLength(replays.filter((r) => r.kind === "incident").length);
    expect(of("class")).toHaveLength(replays.filter((r) => r.kind === "class").length);
    expect(of("incident").length + of("class").length).toBeGreaterThanOrEqual(51);
    expect(of("vendor").map((p) => p.key)).toEqual([...new Set(subjects.map((r) => r.vendor))].sort());
    expect(of("agent").map((p) => p.key)).toEqual(readdirSync(join(PKG, "docs", "hosts")).filter((f) => f.endsWith(".md") && f !== "claude-plugin.md").map((f) => f.replace(/\.md$/, "")).sort());
    for (const c of replays.filter((r) => r.kind === "control")) expect(manifest.pages.some((p) => p.key === c.id)).toBe(false);
    for (const p of [...of("incident"), ...of("class")]) expect(p.path).toBe(`/replays/${p.key}`);
  });

  it("writes only inside replays/pages/, with a do-not-edit header on every file that can carry one", () => {
    expect(Object.keys(files).every((p) => p.startsWith(`${PAGES_DIR}/`))).toBe(true);
    for (const [p, text] of Object.entries(files)) {
      if (p.endsWith(".html")) expect(text.startsWith("<!-- Generated by `pnpm sync:replay-pages`")).toBe(true);
      expect(text).toContain("Do not edit by hand.");
    }
  });

  it("needs no hand-written content outside replays/: the same files come from a root with only the inputs", () => {
    const root = inputsOnly();
    expect(generate(root)).toEqual(files);
  });

  it("is current: the committed pages match the replay files and there is no orphan", () => {
    expect(stale(PKG)).toEqual([]);
    expect(check(PKG).status).toBe(0);
  });
});

describe("replay pages: each incident and class page", () => {
  it("shows the sections in the spec order, with the fix above the first KYA mention in the body", () => {
    for (const r of subjects) {
      const p = manifest.pages.find((x) => x.key === r.id)!;
      const html = body(p);
      const order = ["id=\"what-happens\"", "id=\"the-call\"", "id=\"fix\"", "id=\"what-kya-does\"", "id=\"install\"", "id=\"related\""].map((s) => html.indexOf(s));
      expect(order.every((i) => i > 0), r.id).toBe(true);
      expect([...order].sort((a, b) => a - b), r.id).toEqual(order);
      expect(html, r.id).toContain(`<p>${esc(r.fix!)}</p>`);
      const firstKya = html.search(/KYA|kya|Shield/);
      expect(html.indexOf(esc(r.fix!)), r.id).toBeGreaterThan(0);
      expect(html.indexOf(esc(r.fix!)), r.id).toBeLessThan(firstKya);
      expect(html.indexOf('id="fix"'), r.id).toBeLessThan(firstKya);
    }
  });

  it("shows the call, the rule linked to docs/guard-pack.md, the since version and both install lines", () => {
    for (const r of subjects) {
      const html = body(manifest.pages.find((x) => x.key === r.id)!);
      expect(html, r.id).toContain(`<pre><code>${maskSecrets(esc(r.input.command ?? JSON.stringify((r.input as unknown as Record<string, unknown>), null, 2)))}</code></pre>`);
      expect(html, r.id).toContain(`guard-pack.md" rel="noopener"><code>${r.rule}</code></a>`);
      expect(html, r.id).toContain(`<code>${r.since}</code>`);
      expect(html, r.id).toContain(r.expect === "ask" ? "<strong>Held</strong>" : "<strong>Stopped</strong>");
      expect(html, r.id).toContain("/plugin install kya@shield-kya");
      expect(html, r.id).toContain("npm i -g @shield-agent/kya@latest &amp;&amp; kya start");
    }
  });

  it("labels a reconstructed incident, and only a reconstructed one, and links every source of an incident", () => {
    for (const r of subjects) {
      const html = body(manifest.pages.find((x) => x.key === r.id)!);
      expect(html.includes("Reconstructed from the public account"), r.id).toBe(r.reconstructed === true);
      for (const s of r.sources ?? []) expect(html, r.id).toContain(`href="${esc(s)}"`);
    }
    expect(subjects.some((r) => r.reconstructed)).toBe(true);
  });

  it("gives every page its own title, description and path, a canonical TechArticle JSON-LD that cannot close its script tag", () => {
    for (const k of ["path", "title", "description"] as const) expect(new Set(manifest.pages.map((p) => p[k])).size).toBe(manifest.pages.length);
    for (const p of manifest.pages) {
      expect(p.jsonld, p.path).not.toMatch(/[<>&]/);
      const ld = JSON.parse(p.jsonld);
      expect(ld).toMatchObject({ "@context": "https://schema.org", "@type": "TechArticle", headline: p.title, url: `https://shield-agent.com${p.path}`, mainEntityOfPage: `https://shield-agent.com${p.path}` });
      expect(body(p), p.path).toContain(`<h1>${esc(p.title)}</h1>`);
    }
  });

  it("builds the title from the rule label, and from the replay title where a label is shared", () => {
    const labels = loadLabels(PKG);
    const terraform = manifest.pages.find((p) => p.key === "class-terraform-destroy")!;
    expect(terraform.title).toBe("Stop an agent trying to destroy your infrastructure");
    const nc = manifest.pages.find((p) => p.key === "class-exfil-nc")!;
    expect(nc.title).toBe("Pipe the environment into netcat: how to stop it");
    const curl = manifest.pages.find((p) => p.key === "class-exfil-curl")!;
    expect(curl.title).toBe("Post the environment to a remote host with curl");
    expect(manifest.pages.find((p) => p.key === "2026-04-pocketos-railway-volume")!.title).toBe("Stop an agent trying to delete a cloud volume");
    const counts = new Map<string, number>();
    for (const r of subjects) counts.set(callLabel(r, labels), (counts.get(callLabel(r, labels)) ?? 0) + 1);
    for (const r of subjects) {
      const label = callLabel(r, labels);
      const title = manifest.pages.find((p) => p.key === r.id)!.title;
      if (counts.get(label) === 1) expect(title).toBe(`Stop an agent trying to ${label}`);
      else expect(title).toMatch(r.title.length + ": how to stop it".length <= 60 ? /: how to stop it$/ : /^(Stop an agent trying to |.)/);
    }
  });

  it("keeps titles near 60 characters and descriptions under 156", () => {
    for (const p of manifest.pages) {
      expect(p.title.length, p.title).toBeLessThanOrEqual(65);
      expect(p.description.length, p.description).toBeLessThanOrEqual(155);
    }
  });

  it("tells more than the title on a page: the call, the tool and the vendor, in three sentences", () => {
    for (const r of subjects) {
      const html = body(manifest.pages.find((x) => x.key === r.id)!);
      const happens = /<section id="what-happens"><h2>What happens<\/h2>\n<p>([^]*?)<\/p>/.exec(html)![1];
      expect(happens, r.id).toContain(`The agent sends it through its ${r.tool} tool, and it involves `);
      expect(happens.split(/[.!?](?:\s|$)/).filter(Boolean).length, r.id).toBeGreaterThanOrEqual(3);
    }
  });

  it("a call whose rule label does not fit says what it does: an unset variable wipes the root folder, not the home folder", () => {
    const r = subjects.find((x) => x.id === "class-rm-unset-variable-root")!;
    expect(r.rule).toBe("rm-root-home");
    const page = manifest.pages.find((p) => p.key === r.id)!;
    expect(page.title).toBe("Stop an agent trying to wipe the root folder");
    expect(body(page)).toContain("The call below tries to wipe the root folder.");
    expect(body(page)).not.toContain("home folder");
  });

  it("describes a page with the replay title, the vendor and the first clause of the fix, in 155 characters", () => {
    const rds = subjects.find((x) => x.id === "class-aws-rds-delete-instance")!;
    expect(manifest.pages.find((p) => p.key === rds.id)!.description).toBe("AWS RDS instance deletion. AWS fix: turn on deletion protection for the instance...");
    const tf = subjects.find((x) => x.id === "class-terraform-destroy")!;
    expect(manifest.pages.find((p) => p.key === tf.id)!.description).toBe("Terraform destroy with auto approve. Terraform fix: set lifecycle { prevent_destroy = true } on the resources you cannot lose.");
    for (const r of subjects) {
      const d = manifest.pages.find((p) => p.key === r.id)!.description;
      expect(d.startsWith(`${r.title}. `), r.id).toBe(true);
      expect(d, r.id).toContain(" fix: ");
    }
    expect(firstClause("Turn on the deletion protection of the instance (a, b), then stop. More.")).toBe("Turn on the deletion protection of the instance (a, b)");
    expect(firstClause("In scripts, write the check before you delete anything, then stop.")).toBe("In scripts, write the check before you delete anything");
    expect(describePage({ ...rds, fix: "x".repeat(400) }).length).toBeLessThanOrEqual(155);
  });

  it("agrees with the label the near-miss card uses for every rule", () => {
    const labels = loadLabels(PKG);
    for (const r of subjects) expect(labelOf(r.rule, labels), r.rule).toBe(ruleLabel(r.rule));
  });

  it("escapes markup in a replay: a script tag in a fix, a title or a command is text on the page", () => {
    const root = inputsOnly();
    const f = join(root, "replays", "class-terraform-destroy.yaml");
    writeFileSync(f, readFileSync(f, "utf8").replace("title: Terraform destroy with auto approve", "title: Terraform <b>destroy</b>").replace("terraform destroy -auto-approve", "terraform destroy <script>alert(1)</script>").replace(/fix: >-\n[\s\S]*?\ncredit/, "fix: >-\n  Do not run </script><script>alert(2)</script> and keep a [[${7*7}]] backup of the state file.\ncredit"));
    const out = generate(root) as Record<string, string>;
    const html = out[`${PAGES_DIR}/class-terraform-destroy.html`];
    expect(html).not.toContain("<script>");
    expect(html).not.toContain("<b>");
    expect(html).toContain("&lt;script&gt;alert(1)&lt;/script&gt;");
    expect(html).toContain("[[${7*7}]]");
    // The manifest holds plain text for the description (the site escapes it in the meta tag); the JSON-LD cannot close its tag.
    for (const p of (JSON.parse(out[MANIFEST]) as { pages: Page[] }).pages) expect(p.jsonld, p.path).not.toMatch(/[<>&]/);
  });
});

describe("replay pages: no scanner sees a secret in a generated file", () => {
  // Shapes of the gitleaks default rules and GitHub push protection, written here on their own (not taken from the generator).
  const SHAPES: [string, RegExp][] = [
    ["github-pat", /gh[pousr]_[0-9a-zA-Z]{36}/],
    ["github-fine-grained-pat", /github_pat_\w{22,}/],
    ["stripe", /[sr]k_(?:test|live|prod)_[0-9a-zA-Z]{10,99}/],
    ["slack", /xox[baprs]-[0-9a-zA-Z-]{10,}/],
    ["aws", /(?:A3T[A-Z0-9]|AKIA|ASIA|ABIA|ACCA)[A-Z2-7]{16}/],
    ["private-key", /-----BEGIN[ A-Z0-9_-]{0,100}PRIVATE KEY/],
  ];
  const decode = (t: string) => t.replace(/&#(\d+);/g, (_m, n) => String.fromCodePoint(Number(n))).replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");

  it("no generated file matches a secret shape, although the replay files show placeholders of those shapes", () => {
    const rawInputs = subjects.map((r) => JSON.stringify(r.input));
    for (const [name, shape] of SHAPES) {
      expect(rawInputs.some((t) => shape.test(t)), `${name}: a replay input has this shape, so the check is not empty`).toBe(true);
      for (const [path, text] of Object.entries(files)) expect(shape.test(text), `${name} in ${path}`).toBe(false);
    }
  });

  it("still shows the same text in a browser: decoding the character references gives back the placeholder", () => {
    for (const r of subjects) {
      const shown = decode(body(manifest.pages.find((x) => x.key === r.id)!));
      const cmd = r.input.command ?? "";
      if (cmd) expect(shown, r.id).toContain(cmd);
    }
    const github = decode(body(manifest.pages.find((x) => x.key === "class-secret-write-github")!));
    expect(github).toMatch(/gh[pousr]_[0-9a-zA-Z]{36}/);
    expect(maskSecrets("a ghp_" + "0".repeat(36) + " b")).toBe("a &#103;hp_" + "0".repeat(36) + " b");
  });
});

describe("replay pages: hubs", () => {
  const ids = new Set(subjects.map((r) => r.id));
  const linked = (html: string) => [...html.matchAll(/href="\/replays\/([^"/]+)"/g)].map((m) => m[1]);

  it("list only replays that exist, and every replay of the vendor", () => {
    for (const p of manifest.pages.filter((x) => x.type === "vendor")) {
      const inHub = linked(body(p)).filter((id) => id !== "vendor" && id !== "agent");
      expect(inHub.every((id) => ids.has(id)), p.path).toBe(true);
      expect(inHub.sort()).toEqual(subjects.filter((r) => r.vendor === p.key).map((r) => r.id).sort());
      expect(p.count).toBe(inHub.length);
    }
    for (const p of manifest.pages.filter((x) => x.type !== "vendor" && x.type !== "agent")) {
      const r = subjects.find((x) => x.id === p.key)!;
      const related = linked(body(p)).filter((id) => ids.has(id));
      expect(related.length, p.path).toBeLessThanOrEqual(3);
      for (const id of related) expect(subjects.find((x) => x.id === id)!.vendor, p.path).toBe(r.vendor);
      expect(related, p.path).not.toContain(r.id);
    }
  });

  it("agent hubs list only replays that exist", () => {
    const hubs = manifest.pages.filter((x) => x.type === "agent");
    expect(hubs.length).toBeGreaterThan(0);
    for (const p of hubs) {
      const inHub = linked(body(p)).filter((id) => id !== "vendor" && id !== "agent");
      expect(inHub.every((id) => ids.has(id)), p.path).toBe(true);
      // Not vacuous: a hub lists exactly the replays that ran on its host, so a hub with no replay lists none.
      expect([...inHub].sort(), p.path).toEqual(subjects.filter((r) => r.host === p.key).map((r) => r.id).sort());
      expect(p.count, p.path).toBe(inHub.length);
    }
    expect(hubs.some((p) => linked(body(p)).length > 0)).toBe(true);
  });

  it("say plainly that every replay ran on claude only, and make no claim for another host", () => {
    const claude = manifest.pages.find((p) => p.path === "/replays/agent/claude")!;
    expect(subjects.every((r) => r.host === "claude")).toBe(true);
    expect(body(claude)).toContain(`All ${subjects.length} replays ran on Claude Code only. No replay has run on any other host.`);
    expect(linked(body(claude)).filter((id) => ids.has(id)).sort()).toEqual([...ids].sort());
    const amp = manifest.pages.find((p) => p.path === "/replays/agent/amp")!;
    expect(body(amp)).toContain(`No replay has run on Amp. All ${subjects.length} replays ran on Claude Code only, so this page makes no claim about Amp.`);
    expect(linked(body(amp)).filter((id) => ids.has(id))).toEqual([]);
    expect(body(amp)).toContain("A tool Amp executes outside MCP is outside the gate.");
  });

  it("index a thin hub never: fewer than the minimum replays means noindex", () => {
    for (const p of manifest.pages.filter((x) => x.type === "vendor")) expect(p.index, p.path).toBe(p.count >= MIN_HUB);
    for (const p of manifest.pages.filter((x) => x.type === "agent")) expect(p.index, p.path).toBe(p.count >= 1);
    for (const p of manifest.pages.filter((x) => x.type === "incident" || x.type === "class")) expect(p.index).toBe(true);
  });
});

describe("replay pages: a stale page fails the check", () => {
  it("fails when a replay changes, passes after the generator runs, and fails on an orphan page", () => {
    const root = inputsOnly();
    expect(check(root).status).toBe(1);
    expect(write(root).status).toBe(0);
    expect(check(root).status).toBe(0);
    const f = join(root, "replays", "class-terraform-destroy.yaml");
    writeFileSync(f, readFileSync(f, "utf8").replace("Set lifecycle", "Set the lifecycle block"));
    const stalePage = check(root);
    expect(stalePage.status).toBe(1);
    expect(stalePage.stderr).toContain("replays/pages/class-terraform-destroy.html");
    expect(write(root).status).toBe(0);
    writeFileSync(join(root, PAGES_DIR, "class-removed-replay.html"), "<p>old</p>");
    const orphan = check(root);
    expect(orphan.status).toBe(1);
    expect(orphan.stderr).toContain("class-removed-replay.html (orphan");
    expect(write(root).status).toBe(0);
    expect(existsSync(join(root, PAGES_DIR, "class-removed-replay.html"))).toBe(false);
    expect(check(root).status).toBe(0);
  });

  it("fails when a hand edit changes one generated file", () => {
    const root = inputsOnly();
    write(root);
    const f = join(root, PAGES_DIR, "class-exfil-nc.html");
    writeFileSync(f, readFileSync(f, "utf8").replace("Fix it without us", "Fix it with us"));
    expect(check(root).stderr).toContain("class-exfil-nc.html");
  });
});

describe("replay pages: bad input stops the build", () => {
  const hosts = loadHosts(PKG);
  const labels = loadLabels(PKG);
  it("throws for a rule with no label, an unknown host and a gap", () => {
    const base = replays.find((r) => r.id === "class-terraform-destroy")!;
    expect(() => buildPages([{ ...base, rule: "no-such-rule" }], labels, hosts)).toThrow(/no label for rule no-such-rule/);
    expect(() => buildPages([{ ...base, host: "nohost" }], labels, hosts)).toThrow(/host nohost has no recipe/);
    expect(() => buildPages([{ ...base, status: "gap", expect: "allow" }], labels, hosts)).toThrow(/only a stopped or held replay/);
  });
});

describe("replay pages: links", () => {
  it("unescapes a link in one pass: &amp;lt; stays &lt;", async () => {
    const { unesc } = await import("../scripts/check-replay-links.mjs" as string);
    expect(unesc("a?x=1&amp;y=2")).toBe("a?x=1&y=2");
    expect(unesc("&amp;lt;b&amp;gt;")).toBe("&lt;b&gt;");
    expect(unesc("&lt;&quot;&#39;&gt;")).toBe("<\"'>");
  });

  it("lists every source of every incident, the guard-pack doc and the host recipes", async () => {
    const { pageLinks } = await import("../scripts/check-replay-links.mjs" as string);
    const links = pageLinks(PKG) as string[];
    for (const r of subjects) for (const s of r.sources ?? []) expect(links).toContain(s);
    expect(links).toContain("https://github.com/The-Pixel-Boys/shield-kya/blob/main/docs/guard-pack.md");
    expect(links.filter((l) => l.includes("/docs/hosts/")).length).toBeGreaterThanOrEqual(24);
    expect(links.every((l) => l.startsWith("https://"))).toBe(true);
  });

  it("reports a dead link, a refused one and a network failure with the right verdict", async () => {
    const { checkLinks } = await import("../scripts/check-replay-links.mjs" as string);
    const fake = async (url: string) => {
      if (url.endsWith("/boom")) throw new Error("fetch failed");
      return { status: url.endsWith("/gone") ? 404 : url.endsWith("/bot") ? 403 : 200, body: null };
    };
    const rows = (await checkLinks(["https://x.test/ok", "https://x.test/gone", "https://x.test/bot", "https://x.test/boom"], fake, 1000)) as { verdict: string }[];
    expect(rows.map((r) => r.verdict)).toEqual(["ok", "dead", "unverified", "dead"]);
  });

  it("checks a dead link a second time: a flake passes, a link dead twice stays dead", async () => {
    const { checkLinksWithRetry } = await import("../scripts/check-replay-links.mjs" as string);
    const calls = new Map<string, number>();
    const fake = async (url: string) => {
      const n = (calls.get(url) ?? 0) + 1;
      calls.set(url, n);
      if (url.endsWith("/flake") && n === 1) throw new Error("fetch failed");
      return { status: url.endsWith("/gone") ? 404 : 200, body: null };
    };
    const rows = (await checkLinksWithRetry(["https://x.test/ok", "https://x.test/flake", "https://x.test/gone"], fake, 1000, 1)) as { url: string; verdict: string }[];
    expect(rows.map((r) => r.verdict)).toEqual(["ok", "ok", "dead"]);
    expect(calls.get("https://x.test/ok")).toBe(1);
    expect(calls.get("https://x.test/gone")).toBe(2);
  });

  // Network-gated: KYA_LINKCHECK=1 pnpm test -- replay-pages. Fails on a dead link, so run it before a release.
  it.runIf(process.env.KYA_LINKCHECK === "1")("every link on every page resolves (network)", async () => {
    const { pageLinks, checkLinksWithRetry } = await import("../scripts/check-replay-links.mjs" as string);
    const rows = (await checkLinksWithRetry(pageLinks(PKG))) as { url: string; verdict: string; status: number }[];
    expect(rows.filter((r) => r.verdict === "dead").map((r) => `${r.status} ${r.url}`)).toEqual([]);
  }, 600_000);
});
